#Requires -Version 7
# page_gz.ps1 - gzip the settings page (page.h's raw literal) into page_gz.h, which the QT Py serves with
# Content-Encoding: gzip (fw35: ~4x less to send, so a page load blocks the QT Py's loop that much shorter).
# page_gz.h also checks itself against page.h at compile time (FNV-1a of the page): an edited page.h without a
# re-run of this script fails the build instead of serving the old page.
#
#   page_gz.ps1 [-i page.h] [-o page_gz.h] [-p HOST]
#   -i, --input FILE    the page source (default: page.h next to this script)
#   -o, --output FILE   the header to write (default: page_gz.h next to this script)
#   -p, --push HOST     also upload the page to the QT Py at HOST (fw41+): it serves it from flash at once, no firmware update
#   -h, --help          show this help and exit
param([Parameter(ValueFromRemainingArguments)] [string[]]$Rest)

$in = Join-Path $PSScriptRoot 'page.h'
$out = Join-Path $PSScriptRoot 'page_gz.h'
$push = $null
$usage = @'
Usage: page_gz.ps1 [-i FILE] [-o FILE] [-p HOST]
Gzips the settings page (page.h's raw literal) into page_gz.h for the QT Py firmware.

  -i, --input FILE    the page source (default: page.h next to this script)
  -o, --output FILE   the header to write (default: page_gz.h next to this script)
  -p, --push HOST     also upload the page to the QT Py at HOST (QT Py fw41+): it serves it at once,
                      no firmware update (a firmware update later brings its own page)
  -h, --help          show this help and exit

Examples:
  page_gz.ps1
  page_gz.ps1 --output C:\tmp\page_gz.h
  page_gz.ps1 --push gwolves.local
'@
for ($i = 0; $i -lt $Rest.Count; $i++) {
    $a = $Rest[$i]
    if ($a -eq '--') { if ($i + 1 -lt $Rest.Count) { [Console]::Error.WriteLine("page_gz: unexpected argument '$($Rest[$i + 1])'"); exit 2 }; break }
    $name = $a; $val = $null
    if ($a -match '^(--[a-z-]+)=(.*)$') { $name = $Matches[1]; $val = $Matches[2] }
    switch -regex ($name) {
        '^(-h|--help|-Help)$' { $usage; exit 0 }
        '^(-i|--input|-Input)$' { if ($null -eq $val) { $i++; $val = $Rest[$i] }; if (-not $val) { [Console]::Error.WriteLine("page_gz: $name needs a FILE`nTry 'page_gz.ps1 --help'."); exit 2 }; $in = $val }
        '^(-p|--push|-Push)$' { if ($null -eq $val) { $i++; $val = $Rest[$i] }; if (-not $val) { [Console]::Error.WriteLine("page_gz: $name needs a HOST`nTry 'page_gz.ps1 --help'."); exit 2 }; $push = $val }
        '^(-o|--output|-Output)$' { if ($null -eq $val) { $i++; $val = $Rest[$i] }; if (-not $val) { [Console]::Error.WriteLine("page_gz: $name needs a FILE`nTry 'page_gz.ps1 --help'."); exit 2 }; $out = $val }
        default { [Console]::Error.WriteLine("page_gz: unknown option '$a'`nTry 'page_gz.ps1 --help'."); exit 2 }
    }
}

$ErrorActionPreference = 'Stop'
$src = [IO.File]::ReadAllText((Resolve-Path $in))
$open = 'R"HTML('; $close = ')HTML"'
$a0 = $src.IndexOf($open); $a1 = $src.LastIndexOf($close)
if ($a0 -lt 0 -or $a1 -lt $a0) { [Console]::Error.WriteLine("page_gz: no R`"HTML( ... )HTML`" literal in $in"); exit 1 }
# what the compiler stores: the literal's bytes as UTF-8, line ends as \n (git may check page.h out with CRLF)
$page = $src.Substring($a0 + $open.Length, $a1 - $a0 - $open.Length).Replace("`r`n", "`n")
$bytes = [Text.Encoding]::UTF8.GetBytes($page)
[uint32]$h = 2166136261
foreach ($b in $bytes) { $h = [uint32](([uint64]($h -bxor $b) * 16777619) % 4294967296) }
# the served copy carries <meta name="gw-rest" content="HASH">: FNV-1a of the page with the style emptied, so an open
# page can tell a style-only update (swapped in place) from one that needs a reload (page.h: pgCheck)
$rest = [Text.Encoding]::UTF8.GetBytes([regex]::Replace($page, '(?s)<style>.*?</style>', '<style></style>'))
[uint32]$rh = 2166136261
foreach ($b in $rest) { $rh = [uint32](([uint64]($rh -bxor $b) * 16777619) % 4294967296) }
$served = [Text.Encoding]::UTF8.GetBytes($page.Replace('<meta name="gw-rest" content="">', ('<meta name="gw-rest" content="{0:x8}">' -f $rh)))
$ms = [IO.MemoryStream]::new()
$gz = [IO.Compression.GZipStream]::new($ms, [IO.Compression.CompressionLevel]::SmallestSize, $true)
$gz.Write($served, 0, $served.Length); $gz.Dispose()
$z = $ms.ToArray()
$sb = [Text.StringBuilder]::new()
[void]$sb.Append("#pragma once`n// Generated by page_gz.ps1 from page.h: do not edit. The settings page gzipped (fw35); the check below fails the`n")
[void]$sb.Append("// build when page.h changed since (run page_gz.ps1 again).`n#include `"page.h`"`n`n")
[void]$sb.Append(('#define PAGE_SRC_FNV 0x{0:x8}u  // FNV-1a of the page ({1} bytes)' -f $h, $bytes.Length) + "`n")
[void]$sb.Append("#define PAGE_GZ_LEN $($z.Length)`n`n")
[void]$sb.Append("constexpr uint32_t page_src_fnv(const char* s, size_t n) {`n    uint32_t h = 2166136261u;`n    for (size_t i = 0; i < n; i++) {`n        h = (h ^ (uint8_t) s[i]) * 16777619u;`n    }`n    return h;`n}`n")
[void]$sb.Append("static_assert(page_src_fnv(PAGE_HTML, sizeof(PAGE_HTML) - 1) == PAGE_SRC_FNV, `"page_gz.h is older than page.h: run qtpy/gw_settings/page_gz.ps1`");`n`n")
[void]$sb.Append("static const uint8_t PAGE_GZ[PAGE_GZ_LEN] PROGMEM = {`n")
for ($i = 0; $i -lt $z.Length; $i += 24) {
    $n = [Math]::Min(24, $z.Length - $i)
    [void]$sb.Append('    ' + (($z[$i..($i + $n - 1)] | ForEach-Object { '0x{0:x2}' -f $_ }) -join ', ') + ",`n")
}
[void]$sb.Append("};`n")
[IO.File]::WriteAllText($out, $sb.ToString(), [Text.UTF8Encoding]::new($false))
"page_gz: $($bytes.Length) bytes -> $($z.Length) gzipped ($([Math]::Round(100.0 * $z.Length / $bytes.Length))%), fnv 0x{0:x8}, gw-rest {1:x8} -> $out" -f $h, $rh
if ($push) {
    $tmp = Join-Path ([IO.Path]::GetTempPath()) 'page.gz'
    [IO.File]::WriteAllBytes($tmp, $z)
    $r = & curl.exe -s -m 20 -F "file=@$tmp;filename=page.gz" "http://$push/api/page"
    Remove-Item $tmp -ErrorAction SilentlyContinue
    if ($LASTEXITCODE -ne 0) { [Console]::Error.WriteLine("page_gz: upload to $push failed (curl exit $LASTEXITCODE)"); exit 1 }
    "page_gz: pushed to ${push}: $r"
    if ($r -notmatch '"ok":true') { exit 1 }
}